import {mkdtemp,mkdir,cp,readFile,writeFile,rename} from 'node:fs/promises';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
await mkdir('review/.tools',{recursive:true});
const fixture=await mkdtemp(resolve('review/.tools/build-fixture-'));
for(const dir of ['scripts','public','netlify','supabase'])await cp(dir,resolve(fixture,dir),{recursive:true});
await mkdir(resolve(fixture,'review'));
for(const file of ['package.json','robots.txt','sitemap.xml','review/protected-hashes.json','review/original-structured-data.json','review/Manolinq-original-2026-09-16.zip'])await cp(file,resolve(fixture,file));
const run=()=>spawnSync(process.execPath,['scripts/build.mjs'],{cwd:fixture,encoding:'utf8'});
const checks=[];
let result=run();assert.equal(result.status,0,result.stderr);checks.push('Fresh production output builds from source only');
const image=resolve(fixture,'public/images/portfolio/studio-kleur-desktop.webp');
const saved=await readFile(image),missing=resolve(fixture,'public/images/portfolio/omitted.webp');
await rename(image,missing);
result=run();assert.notEqual(result.status,0);assert.match(result.stderr,/Missing asset or filename case mismatch/);checks.push('Missing source image stops build even when stale output still contains it');
await rename(missing,image);
const wrongCase=resolve(fixture,'public/images/portfolio/Studio-kleur-desktop.webp');
await rename(image,missing);await rename(missing,wrongCase);
result=run();assert.notEqual(result.status,0);assert.match(result.stderr,/filename case mismatch/);checks.push('Wrong filename case stops build on Windows as well as Linux');
await rename(wrongCase,missing);await rename(missing,image);
await writeFile(image,'<!doctype html><h1>Not an image</h1>');
result=run();assert.notEqual(result.status,0);assert.match(result.stderr,/Not a nonempty WebP/);checks.push('HTML masquerading as WebP stops build');
await writeFile(image,saved);
const cssPath=resolve(fixture,'public/styles/site.css');
const first=JSON.parse(await readFile(resolve(fixture,'site-dist/portfolio-build.json'),'utf8'));
await writeFile(cssPath,(await readFile(cssPath,'utf8'))+'\n/* isolated fingerprint regression fixture */\n');
await writeFile(resolve(fixture,'index.html'),'stale generated page');
result=run();assert.equal(result.status,0,result.stderr);
const second=JSON.parse(await readFile(resolve(fixture,'site-dist/portfolio-build.json'),'utf8'));
assert.notEqual(first.stylesheet.url,second.stylesheet.url);
assert.ok((await readFile(resolve(fixture,'site-dist/index.html'),'utf8')).includes(second.stylesheet.url));
checks.push('Build alone regenerates stale HTML and updates CSS fingerprint');
const protectedPath=resolve(fixture,'netlify/functions/submit-lead.js');
await writeFile(protectedPath,(await readFile(protectedPath,'utf8'))+'\n// isolated corruption fixture\n');
result=run();assert.notEqual(result.status,0);assert.match(result.stderr,/Protected original changed/);checks.push('Original protected-file gate still rejects backend modification');
await writeFile('review/repair/build-integrity-results.json',JSON.stringify({checks,passed:true},null,2));
console.log(JSON.stringify({checks:checks.length,passed:true}));
